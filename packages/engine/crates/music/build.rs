//! Generates the music types' table (`types.rs`, N2) from the installed
//! LilyPond 2.26.0's `scm/lily/define-music-types.scm`, never committed:
//! for each of `music-descriptions`' types, sorted by name as the file sorts
//! them, its name, its `types` and its other properties but `description`,
//! each as the Scheme text that gives its value in `(lily)`. `LILY_SCM`
//! names another `scm/lily/`. Without one, the table is empty and
//! `make-music` finds no type.
//!
//! And the event classes' table (`event_class.rs`, N3) from
//! `define-event-classes.scm`'s `event-classes`: each class with its
//! parent's index, in the file's order, a class named twice kept where it
//! is first, as `ly:make-event-class` finds it. Without the file it is
//! empty, and the classes are numbered as they are met.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-env-changed=LILY_SCM");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let lily = lily_scm();
    let classes = match &lily {
        Some(lily) => {
            let path = lily.join("define-event-classes.scm");
            println!("cargo::rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            event_classes(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        }
        None => Vec::new(),
    };
    let mut table =
        String::from("// Generated by build.rs from define-event-classes.scm; never committed.\n");
    let _ = writeln!(
        table,
        "pub static EVENT_CLASSES: [(&str, Option<u8>); {}] = {classes:?};",
        classes.len()
    );
    std::fs::write(out.join("event_classes.rs"), table).expect("event_classes.rs");
    let types = match &lily {
        Some(lily) => {
            let path = lily.join("define-music-types.scm");
            println!("cargo::rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            parse(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        }
        None => {
            println!("cargo::warning=no LilyPond 2.26.0: the music types' table is empty");
            Vec::new()
        }
    };
    std::fs::write(out.join("music_types.rs"), generate(&types)).expect("music_types.rs");
}

/// `scm/lily/` from `LILY_SCM`, or of the `lilypond` on the path if it is
/// 2.26.0, as `tests/support` of the parser finds it.
fn lily_scm() -> Option<PathBuf> {
    if let Some(dir) = std::env::var_os("LILY_SCM") {
        return Some(PathBuf::from(dir));
    }
    let version = Command::new("lilypond").arg("--version").output().ok()?;
    if !String::from_utf8_lossy(&version.stdout).contains("GNU LilyPond 2.26.0") {
        return None;
    }
    let path = Command::new("sh")
        .args(["-c", "command -v lilypond"])
        .output()
        .ok()?;
    let binary = std::fs::canonicalize(String::from_utf8(path.stdout).ok()?.trim()).ok()?;
    let lily = binary.parent()?.join("../share/lilypond/2.26.0/scm/lily");
    lily.join("define-music-types.scm").exists().then_some(lily)
}

struct Type {
    name: String,
    types: Vec<String>,
    /// Its properties in the file's order, `description` left out: the key
    /// and the Scheme text of the value, quoted unless it was unquoted.
    props: Vec<(String, String)>,
}

/// Reads `music-descriptions`' quasiquoted list, `((Name . ((key . value)
/// …)) …)`, sorted by name as `(sort music-descriptions alist<?)` sorts it.
fn parse(text: &str) -> Result<Vec<Type>, String> {
    let r = Reader {
        b: text.as_bytes(),
        text,
    };
    let start = text
        .find("(define-public music-descriptions")
        .ok_or("no music-descriptions")?;
    let quasi = text[start..].find("`(").ok_or("no `(")? + start;
    let mut i = r.ws(quasi + 2);
    let mut types = Vec::new();
    while r.b[i] != b')' {
        // (Name . ((key . value) …))
        i = r.expect(i, b'(')?;
        let (name, at) = r.atom(i);
        i = r.expect(r.expect(at, b'.')?, b'(')?;
        let mut t = Type {
            name: name.into(),
            types: Vec::new(),
            props: Vec::new(),
        };
        while r.b[i] != b')' {
            i = r.expect(i, b'(')?;
            let (key, at) = r.atom(i);
            i = r.expect(at, b'.')?;
            let unquoted = r.b[i] == b',';
            let from = if unquoted { i + 1 } else { i };
            let end = r.datum(from)?;
            let value = r.text[from..end].trim();
            if key == "types" {
                t.types = value
                    .trim_matches(['(', ')'])
                    .split_whitespace()
                    .map(String::from)
                    .collect();
            }
            if key != "description" {
                let value = if unquoted {
                    value.into()
                } else {
                    format!("'{value}")
                };
                t.props.push((key.into(), value));
            }
            i = r.expect(r.ws(end), b')')?;
        }
        i = r.expect(r.expect(i, b')')?, b')')?;
        types.push(t);
    }
    types.sort_by(|a, b| a.name.cmp(&b.name));
    if types.len() > usize::from(u8::MAX) {
        return Err(format!("{} types do not fit a u8", types.len()));
    }
    Ok(types)
}

/// `event-classes`' `((parent . (child …)) …)`: each class and its
/// parent's index, `()` for none, in order; at most 256 of them.
fn event_classes(text: &str) -> Result<Vec<(String, Option<u8>)>, String> {
    let r = Reader {
        b: text.as_bytes(),
        text,
    };
    let start = text
        .find("(define event-classes")
        .ok_or("no event-classes")?;
    let mut i = r.expect(text[start..].find("'(").ok_or("no '(")? + start + 1, b'(')?;
    let mut classes: Vec<(String, Option<u8>)> = Vec::new();
    while r.b[i] != b')' {
        i = r.expect(i, b'(')?;
        let parent = if r.b[i] == b'(' {
            i = r.expect(r.expect(i, b'(')?, b')')?;
            None
        } else {
            let (name, at) = r.atom(i);
            i = at;
            let index = classes.iter().position(|(c, _)| c == name);
            Some(index.ok_or(format!("{name} before its parent"))? as u8)
        };
        i = r.expect(r.expect(i, b'.')?, b'(')?;
        while r.b[i] != b')' {
            let (name, at) = r.atom(i);
            if !classes.iter().any(|(c, _)| c == name) {
                classes.push((name.into(), parent));
            }
            i = at;
        }
        i = r.expect(r.expect(i, b')')?, b')')?;
    }
    if classes.len() > 256 {
        return Err(format!("{} event classes do not fit a u8", classes.len()));
    }
    Ok(classes)
}

/// Just enough of a Scheme reader for the file: lists, strings, atoms,
/// quotes and comments, by their extents.
struct Reader<'a> {
    b: &'a [u8],
    text: &'a str,
}

impl Reader<'_> {
    /// The first byte at or after `i` that is no space and in no comment.
    fn ws(&self, mut i: usize) -> usize {
        while i < self.b.len() {
            match self.b[i] {
                b';' => {
                    while i < self.b.len() && self.b[i] != b'\n' {
                        i += 1;
                    }
                }
                c if c.is_ascii_whitespace() => i += 1,
                _ => break,
            }
        }
        i
    }

    fn expect(&self, i: usize, c: u8) -> Result<usize, String> {
        let i = self.ws(i);
        if self.b.get(i) == Some(&c) {
            Ok(self.ws(i + 1))
        } else {
            let line = self.text[..i].matches('\n').count() + 1;
            Err(format!("line {line}: expected {}", c as char))
        }
    }

    /// The atom at `i` and where the next datum begins.
    fn atom(&self, i: usize) -> (&str, usize) {
        let i = self.ws(i);
        let mut end = i;
        while end < self.b.len()
            && !self.b[end].is_ascii_whitespace()
            && !matches!(self.b[end], b'(' | b')')
        {
            end += 1;
        }
        (&self.text[i..end], self.ws(end))
    }

    /// The end of the datum that begins at `i`.
    fn datum(&self, i: usize) -> Result<usize, String> {
        let i = self.ws(i);
        match self.b.get(i) {
            Some(b'(') => {
                let mut j = self.ws(i + 1);
                while self.b.get(j) != Some(&b')') {
                    if j >= self.b.len() {
                        return Err("unclosed list".into());
                    }
                    j = self.ws(self.datum(j)?);
                }
                Ok(j + 1)
            }
            Some(b'"') => {
                let mut j = i + 1;
                while j < self.b.len() && self.b[j] != b'"' {
                    j += if self.b[j] == b'\\' { 2 } else { 1 };
                }
                Ok(j + 1)
            }
            Some(b'\'' | b'`' | b',') => self.datum(i + 1),
            Some(_) => Ok(i + self.atom(i).0.len()),
            None => Err("end of file in a datum".into()),
        }
    }
}

fn generate(types: &[Type]) -> String {
    let mut out =
        String::from("// Generated by build.rs from define-music-types.scm; never committed.\n");
    let _ = writeln!(out, "pub static TYPES: [MusicType; {}] = [", types.len());
    for t in types {
        let _ = writeln!(out, "    MusicType {{");
        let _ = writeln!(out, "        name: {:?},", t.name);
        let _ = writeln!(out, "        types: &{:?},", t.types);
        let props: Vec<(&str, &str)> = t
            .props
            .iter()
            .map(|(k, v)| (k.as_str(), v.as_str()))
            .collect();
        let _ = writeln!(out, "        props: &{props:?},");
        let _ = writeln!(out, "    }},");
    }
    out.push_str("];\n");
    out
}
